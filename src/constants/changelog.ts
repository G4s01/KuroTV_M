export function formatChangelog(entry: ChangelogEntry): string {
  const lines: string[] = [
    `=== ${entry.title} (V${entry.version} BUILD ${entry.versionCode}) ===`,
    `DATA DI RILASCIO: ${entry.releaseDate}`,
    '',
    ...entry.highlights.map((h, i) => `${i + 1}. ${h}`),
  ];
  return lines.join('\n');
}
